import { HttpClient, HttpParams } from '@angular/common/http';
import { Injectable, inject } from '@angular/core';
import { Observable, catchError, map, throwError } from 'rxjs';
import { ApiError } from '../errors/api-error';
import {
  CreateCityRequest,
  GeneratedCity,
  GeneratedCityDetail,
  GeneratedCityPage,
  GenreOption,
  ImportStatus,
  Me,
  PipelineRun,
  UserDataDeletionResult,
} from './api.models';
import { localizeDetail } from './city-labels';
import { RecipeSchema } from './recipe.models';

/** Calls to CityFy.Api (/api/v1, same origin through the dev-server proxy). Errors are ApiError. */
@Injectable({ providedIn: 'root' })
export class ApiService {
  private readonly http = inject(HttpClient);
  private readonly base = '/api/v1';

  me(): Observable<Me> {
    return this.wrap(this.http.get<Me>(`${this.base}/me`));
  }

  logout(): Observable<void> {
    return this.wrap(this.http.post<void>(`${this.base}/auth/logout`, null));
  }

  /** Full-page navigation to Spotify: the login is not an XHR. */
  loginUrl(returnUrl: string): string {
    return `${this.base}/auth/login?returnUrl=${encodeURIComponent(returnUrl)}`;
  }

  // --- Saved cities (generated by the backend: data + map) ------------------------

  cities(page: number, pageSize: number): Observable<GeneratedCityPage> {
    return this.wrap(this.http.get<GeneratedCityPage>(`${this.base}/cities`, { params: new HttpParams().set('page', page).set('pageSize', pageSize) }));
  }

  /** City and map are null until the generation is Done. */
  generatedCity(cityId: string): Observable<GeneratedCityDetail> {
    return this.wrap(this.http.get<GeneratedCityDetail>(`${this.base}/cities/${encodeURIComponent(cityId)}`)).pipe(map(localizeDetail));
  }

  /** Queues a generation (or returns the identical city already there). */
  createCity(request: CreateCityRequest): Observable<GeneratedCity> {
    return this.wrap(this.http.post<GeneratedCity>(`${this.base}/cities`, request));
  }

  deleteCity(cityId: string): Observable<void> {
    return this.wrap(this.http.delete<void>(`${this.base}/cities/${encodeURIComponent(cityId)}`));
  }

  cancelCity(cityId: string): Observable<GeneratedCity> {
    return this.wrap(this.http.post<GeneratedCity>(`${this.base}/cities/${encodeURIComponent(cityId)}/cancel`, null));
  }

  /** Keys, ranges and presets of the parameter string of a custom map. */
  recipeSchema(): Observable<RecipeSchema> {
    return this.wrap(this.http.get<RecipeSchema>(`${this.base}/cities/recipe/schema`));
  }

  /** Genres and subgenres listened in [from, to) (CITY_CATALOG_MISSING while the first import runs). */
  genreOptions(from: string | null, to: string | null): Observable<GenreOption[]> {
    let params = new HttpParams();
    if (from) params = params.set('from', from);
    if (to) params = params.set('to', to);
    return this.wrap(this.http.get<GenreOption[]>(`${this.base}/city/genres`, { params }));
  }

  runs(limit = 5): Observable<PipelineRun[]> {
    return this.wrap(this.http.get<PipelineRun[]>(`${this.base}/pipeline/runs`, { params: new HttpParams().set('limit', limit) }));
  }

  /** Recomputes the user's artist catalog now, from all the plays already imported (any source). */
  rebuild(): Observable<PipelineRun> {
    return this.wrap(this.http.post<PipelineRun>(`${this.base}/city/rebuild`, null));
  }

  /** Deletes everything Cityfy keeps about the user; the session is closed by the server. */
  deleteMyData(): Observable<UserDataDeletionResult> {
    return this.wrap(this.http.delete<UserDataDeletionResult>(`${this.base}/me/data`));
  }

  upload(file: File): Observable<{ uploadId: string }> {
    const form = new FormData();
    form.append('file', file, file.name);
    return this.wrap(this.http.post<{ uploadId: string }>(`${this.base}/uploads`, form));
  }

  uploadStatus(uploadId: string): Observable<ImportStatus> {
    return this.wrap(this.http.get<ImportStatus>(`${this.base}/uploads/${encodeURIComponent(uploadId)}`));
  }

  sync(): Observable<{ jobId: string }> {
    return this.wrap(this.http.post<{ jobId: string }>(`${this.base}/spotify/sync`, null));
  }

  syncStatus(jobId: string): Observable<ImportStatus> {
    return this.wrap(this.http.get<ImportStatus>(`${this.base}/spotify/sync/${encodeURIComponent(jobId)}`));
  }

  private wrap<T>(request: Observable<T>): Observable<T> {
    return request.pipe(catchError((e) => throwError(() => ApiError.from(e))));
  }
}
